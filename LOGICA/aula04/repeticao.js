// Declarar uma variável chamada contador que receba um valor numérico
let contador = 0

// Enquanto contador for melhor do que 10 repita
while (contador < 10) {
    console.log("OLHA A HORA DO CAFÉ");
    console.log("VENHA TOMAR CAFÉ!");
    console.log("CAFÉ DA MANHÃ, CAFÉ DA TARDE! NÃO IMPORTA!");
    console.log("VENHA TOMAR CAFÉ!!!");
    
    // Adicionar ++ após o nome de uma variável faz com que seja adicionado 1 ao seu valor
    contador++
    console.log(contador);
}